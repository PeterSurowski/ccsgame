function toPath(word) {
  return [...word.toUpperCase()].map((letter, index) => (
    (glyphs[letter] || glyphs['?'])
      .flatMap((row, y) => [...row].map((pixel, x) => (pixel === '1'
        ? `M${index * 6 + x} ${y}h1v1h-1z` : '')))
      .join('')
  )).join('')
}

export default function PixelText({ text }) {
  return <p className="pixel-text">
    <span className="flashback-readable">{text}</span>
    <span aria-hidden="true">{text.split(' ').map((word, index) => <span key={index}>
      <svg className="pixel-word" viewBox={`0 0 ${word.length * 6} 7`}
        style={{ width: `${word.length * 6 / 7}em` }} focusable="false">
        <path d={toPath(word)} />
      </svg>{' '}
    </span>)}</span>
  </p>
}
